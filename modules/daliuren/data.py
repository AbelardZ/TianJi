def ke(a, b):
    """五行 a 是否克五行 b。"""
    return KE[a] == b


def wx_of(token):
    """天干或地支的五行。"""
    return GAN_WX[token] if token in GAN_WX else ZHI_WX[token]


def liuqin(zhi, day_gan):
    """以日干为「我」定六亲。"""
    me = GAN_WX[day_gan]
    w = ZHI_WX[zhi]
    if w == me:
        return '兄弟'
    if SHENG[w] == me:
        return '父母'
    if SHENG[me] == w:
        return '子孙'
    if KE[me] == w:
        return '妻财'
    return '官鬼'


def gong_wx_list(gong):
    """地盘一宫参与涉害计害的五行：本气 + 十干寄宫之干。"""
    return [ZHI_WX[gong]] + [GAN_WX[g] for g in GONG_JI_GAN.get(gong, ())]


def meng_rank(gong):
    return 3 if gong in MENG else (2 if gong in ZHONG else 1)
