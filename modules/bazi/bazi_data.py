def get_shishen(day_gan, other_gan):
    """计算天干 other_gan 相对日干 day_gan 的十神。

    规则(以日干为"我"):
    - 同五行同性 -> 比肩; 同五行异性 -> 劫财
    - 我生同性 -> 食神; 我生异性 -> 伤官
    - 我克同性 -> 偏财; 我克异性 -> 正财
    - 克我同性 -> 七杀; 克我异性 -> 正官
    - 生我同性 -> 偏印; 生我异性 -> 正印
    """
    if day_gan == other_gan:
        return '比肩'
    same_yin = YINYANG_GAN[day_gan] == YINYANG_GAN[other_gan]
    w_day = GAN_WUXING[day_gan]
    w_other = GAN_WUXING[other_gan]
    # 生我者印
    if SHENG[w_other] == w_day:
        return '偏印' if same_yin else '正印'
    # 我生者食伤
    if SHENG[w_day] == w_other:
        return '食神' if same_yin else '伤官'
    # 克我者官杀
    if KE[w_other] == w_day:
        return '七杀' if same_yin else '正官'
    # 我克者财
    if KE[w_day] == w_other:
        return '偏财' if same_yin else '正财'
    # 同五行(非同性即异性) -> 劫财
    return '劫财'


